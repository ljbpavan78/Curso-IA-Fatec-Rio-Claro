"""Peça ao usuário um número inteiro e exiba o dobro, o triplo e a metade desse
número."""
num = int(input("Digite um número inteiro: "))
dobro = num * 2
triplo = num * 3
metade = num / 2
print ("O dobro de " + str(num) + " é: " + str(dobro))
print ("O triplo de " + str(num) + " é: " + str(triplo))
print ("A metade de " + str(num) + " é: " + str(metade))